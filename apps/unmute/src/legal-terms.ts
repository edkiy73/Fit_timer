export interface TermsDetails {
  owner?: string;
  country?: string;
  email?: string;
  ageFrom?: number;
}

/** The terms with the owner's details in place; a missing detail keeps a visible blank. */
export function fillTerms(text: string, legal: TermsDetails | null | undefined): string {
  const value = (raw: unknown, blank: string) => String(raw ?? '').trim() || blank;
  return text
    .replace(/\{owner\}/g, value(legal?.owner, '[владелец приложения]'))
    .replace(/\{country\}/g, value(legal?.country, '[страна]'))
    .replace(/\{email\}/g, value(legal?.email, '[почта для обращений]'))
    .replace(/\{ageFrom\}/g, value(legal?.ageFrom, '14'));
}
