// Generates supabase/migrations/20261027130000_fe_catalog.sql from the approved prototype V21:
// topic categories, topics (incl. admin-hidden ones, flagged hidden), descriptions, identity options and cities.
// Re-run after the prototype catalog changes: node tools/gen-fe-catalog.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const html = readFileSync(new URL('../public/prototype-v21.html', import.meta.url), 'utf8').split('\n');
const start = html.findIndex(l => l.startsWith('const TOPICS={'));
const end = html.findIndex((l, i) => i > start && l.startsWith('const CITY='));
if (start < 0 || end < 0) throw new Error('catalog block not found in prototype-v21.html');
const src = html.slice(start, end + 1).join('\n');
const ctx = { L: (ru) => ru };
vm.createContext(ctx);
vm.runInContext(src + '\n;globalThis.out={TOPICS,HIDDEN_TOPICS,TOPIC_DESC,CATS,OPT,CITY,ADMIN_HIDDEN_TOPICS};', ctx);
const { TOPICS, HIDDEN_TOPICS, TOPIC_DESC, CATS, OPT, CITY, ADMIN_HIDDEN_TOPICS } = ctx.out;

const q = v => v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const lines = [];
lines.push('-- GENERATED by tools/gen-fe-catalog.mjs from public/prototype-v21.html. Do not edit by hand.');
lines.push('-- Catalogs for interests (topics) and profile details. Admin-editable later; codes are stable ids.');
lines.push('');
lines.push(`insert into feture.topic_category (id, ru, en, plate, position) values`);
lines.push(CATS.map((c, i) => `  (${q(c.id)}, ${q(c.ru)}, ${q(c.en)}, ${q(c.pl)}, ${i})`).join(',\n') + '\non conflict (id) do update set ru = excluded.ru, en = excluded.en, plate = excluded.plate, position = excluded.position;');
lines.push('');
const all = { ...TOPICS, ...HIDDEN_TOPICS };
const ids = Object.keys(all);
lines.push(`insert into feture.topic (id, category_id, ru, en, desc_ru, desc_en, position, hidden) values`);
lines.push(ids.map((id, i) => {
  const t = all[id], d = TOPIC_DESC[id];
  return `  (${q(id)}, ${q(t.cat)}, ${q(t.ru)}, ${q(t.en)}, ${q(d?.ru)}, ${q(d?.en)}, ${i}, ${ADMIN_HIDDEN_TOPICS.includes(id)})`;
}).join(',\n') + '\non conflict (id) do update set category_id = excluded.category_id, ru = excluded.ru, en = excluded.en, desc_ru = excluded.desc_ru, desc_en = excluded.desc_en, position = excluded.position, hidden = excluded.hidden;');
lines.push('');
const kinds = { gender: 'gender', orient: 'orient', role: 'role', status: 'status', format: 'format', seek: 'seek' };
lines.push(`insert into feture.profile_option (kind, code, ru, en, position) values`);
lines.push(Object.keys(kinds).flatMap(k => (OPT[k] || []).map(([code, ru, en], i) => `  (${q(k)}, ${q(code)}, ${q(ru)}, ${q(en)}, ${i})`)).join(',\n') + '\non conflict (kind, code) do update set ru = excluded.ru, en = excluded.en, position = excluded.position;');
lines.push('');
const cities = Object.entries(CITY).filter(([id]) => id !== 'online');
const country = { berlin: 'DE', hamburg: 'DE', moscow: 'RU' };
lines.push(`insert into feture.place (code, country, name_ru, name_en, state) values`);
lines.push(cities.map(([id, c]) => `  (${q(id)}, ${q(country[id] ?? 'DE')}, ${q(c.ru)}, ${q(c.en)}, 'approved')`).join(',\n') + '\non conflict (code) do nothing;');
lines.push('');
writeFileSync(new URL('../supabase/migrations/20261027130000_fe_catalog.sql', import.meta.url), lines.join('\n'));
console.log(`categories ${CATS.length}, topics ${ids.length} (hidden ${ADMIN_HIDDEN_TOPICS.length}), options ${Object.keys(kinds).map(k => k + ' ' + (OPT[k] || []).length).join(', ')}, cities ${cities.length}`);
