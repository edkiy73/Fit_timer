// Generates src/fe/v21.css from public/prototype-v21.html: the prototype's own stylesheet, scoped under `.v21`
// so the screens moved to /api/fe look exactly like V21 while the current screens stay untouched.
// Run: node tools/gen-v21-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

const html = readFileSync(new URL('../public/prototype-v21.html', import.meta.url), 'utf8');
const start = html.indexOf('<style>') + '<style>'.length;
const css = html.slice(start, html.indexOf('</style>', start));

const scope = sel => sel.split(',').map(s => s.trim()).filter(Boolean).map(s => {
  if (s.startsWith(':root')) {
    const rest = s.slice(5);
    const m = rest.match(/^((?::not\([^)]*\)|\[[^\]]*\])*)(.*)$/);
    const cond = m[1], tail = m[2].trim();
    return (cond ? `:root${cond} ` : '') + '.v21' + (tail ? ' ' + tail : '');
  }
  if (/^(html|body)(\b|$)/.test(s)) return '.v21' + s.replace(/^(html|body)/, '');
  return '.v21 ' + s;
}).join(',\n');

const root = postcss.parse(css);
root.walkRules(rule => {
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
  rule.selector = scope(rule.selector);
});
// Design system (owner, 28.10.2026): the prototype's literal font sizes and radii become kit tokens
// (src/fe/kit/tokens.css), so changing a token changes every screen. Half-pixel sizes snap to the nearest step.
const FS = [[11, '--fs-micro'], [12, '--fs-cap'], [13, '--fs-xs'], [14, '--fs-sm'], [15, '--fs-body'], [16, '--fs-md'], [17, '--fs-h4'],
  [19, '--fs-h3'], [22, '--fs-h2'], [26, '--fs-h1s'], [28, '--fs-h1']];
const RADII = [[4, '--r-2xs'], [8, '--r-xs'], [10, '--r-s'], [12, '--r-m'], [14, '--r'], [18, '--r-l'], [24, '--r-xl']];
const nearest = (list, v) => list.reduce((a, b) => Math.abs(b[0] - v) < Math.abs(a[0] - v) ? b : a)[1];
const fsVar = px => px > 30 ? null : `var(${nearest(FS, px)})`;
const rVar = px => px >= 60 ? 'var(--r-full)' : px > 30 ? null : px === 0 ? null : `var(${nearest(RADII, px)})`;
root.walkDecls(d => {
  if (d.parent?.parent?.type === 'atrule' && /keyframes$/i.test(d.parent.parent.name)) return;
  if (d.prop === 'font-size') { const m = d.value.match(/^([\d.]+)px$/); const v = m && fsVar(+m[1]); if (v) d.value = v; }
  else if (d.prop === 'font') d.value = d.value.replace(/(^|\s)([\d.]+)px(?=\/|\s)/, (all, pre, n) => { const v = fsVar(+n); return v ? pre + v : all; });
  else if (d.prop === 'border-radius') d.value = d.value.split(/\s+/).map(x => { const m = x.match(/^([\d.]+)px$/); const v = m && rVar(+m[1]); return v ?? x; }).join(' ');
});
const header = '/* GENERATED by tools/gen-v21-css.mjs from public/prototype-v21.html. Do not edit by hand. */\n';
writeFileSync(new URL('../src/fe/v21.css', import.meta.url), header + root.toString());
console.log('rules:', root.nodes.length);
