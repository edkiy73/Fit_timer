// Builds the city catalog migration from GeoNames (https://www.geonames.org, CC BY 4.0 — credited in the «copyright» document).
//   node tools/build-cities.mjs <dir with cities15000.txt and alternateNamesV2.txt>
// Writes supabase/migrations/20261106000300_fe_cities_15k.sql: every city GeoNames lists in cities15000 (15 000+ people and
// the seats of regions — about 34 000) with its Russian and English names (preferred alternate name, else the GeoNames name;
// no Russian name: the English one), its coordinates, population and time zone. Idempotent: a city already in feture.place
// (the seeded ones, matched by country and name; those of 20261106000100) only gains the missing data; the rest are added
// as approved places. Nobody types a city (owner 06.11.2026): the app searches this table on the server (place.search).
// Source files (download once): download.geonames.org/export/dump/cities15000.zip (3.4 MB), alternateNamesV2.zip (205 MB).
import fs from 'node:fs';
import readline from 'node:readline';

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-cities.mjs <geonames dir>'); process.exit(1); }
const MIN_POP = 0; // cities15000 already holds only 15 000+ places and the seats of regions

const cities = new Map();
for (const line of fs.readFileSync(dir + '/cities15000.txt', 'utf8').split('\n')) {
  if (!line) continue;
  const f = line.split('\t');
  const pop = Number(f[14]), capital = f[7] === 'PPLC';
  if (pop < MIN_POP && !capital) continue;
  cities.set(f[0], { id: Number(f[0]), country: f[8], name: f[1], lat: Number(f[4]), lon: Number(f[5]), pop, tz: f[17] || null, ru: null, en: null, ruScore: -1, enScore: -1 });
}
console.error('cities', cities.size);

// alternateNamesV2: id, geonameid, isolanguage, name, isPreferred, isShort, isColloquial, isHistoric, from, to
const rl = readline.createInterface({ input: fs.createReadStream(dir + '/alternateNamesV2.txt', 'utf8'), crlfDelay: Infinity });
for await (const line of rl) {
  const f = line.split('\t');
  const lang = f[2];
  if (lang !== 'ru' && lang !== 'en') continue;
  const c = cities.get(f[1]);
  if (!c || f[6] === '1' || f[7] === '1') continue; // colloquial and historic names are not shown
  const score = (f[4] === '1' ? 2 : 0) + (f[5] === '1' ? 0 : 1);
  if (lang === 'ru' && score > c.ruScore) { c.ru = f[3]; c.ruScore = score; }
  if (lang === 'en' && score > c.enScore) { c.en = f[3]; c.enScore = score; }
}

const q = s => s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'";
const rows = [...cities.values()].sort((a, b) => b.pop - a.pop).map(c => {
  const en = c.en ?? c.name, ru = c.ru ?? en; // no Russian name: the English one stands in (the screens read name_ru)
  return `(${c.id}, '${c.country}', ${q(ru)}, ${q(en)}, ${c.lat.toFixed(3)}, ${c.lon.toFixed(3)}, ${c.pop}, ${q(c.tz)})`;
});
const chunks = [];
for (let i = 0; i < rows.length; i += 1000) chunks.push(rows.slice(i, i + 1000).join(',\n'));

const sql = `-- The city catalog (owner 06.11.2026): ${rows.length} cities from GeoNames (cities15000, CC BY 4.0).
-- Generated by tools/build-cities.mjs — do not edit by hand. Idempotent: reruns add nothing twice.
create temp table _geo (geoname_id int, country text, name_ru text, name_en text, lat float8, lon float8, population int, tz text) on commit drop;
${chunks.map(c => `insert into _geo values\n${c};`).join('\n')}

-- A seeded city (same country, same name in one of the languages) keeps its row and its code; it gains the geo data.
-- A city of the first load (20261106000100) is found by its GeoNames id and gains its time zone.
update feture.place p set tz = g.tz, population = coalesce(p.population, g.population) from _geo g where p.geoname_id = g.geoname_id;

update feture.place p set geoname_id = g.geoname_id, population = g.population, tz = g.tz, lat = coalesce(p.lat, g.lat), lon = coalesce(p.lon, g.lon)
  from _geo g
 where p.geoname_id is null and p.country = g.country
   and (lower(split_part(p.name_en, ',', 1)) = lower(g.name_en) or lower(split_part(p.name_ru, ',', 1)) = lower(g.name_ru) or lower(split_part(p.name_en, ',', 1)) = lower(g.name_ru))
   and not exists (select 1 from feture.place o where o.geoname_id = g.geoname_id);

insert into feture.place (country, name_ru, name_en, state, lat, lon, geoname_id, population, tz)
select g.country, g.name_ru, g.name_en, 'approved', g.lat, g.lon, g.geoname_id, g.population, g.tz from _geo g
 where not exists (select 1 from feture.place p where p.geoname_id = g.geoname_id)
   and not exists (select 1 from feture.place p where p.country = g.country and p.state = 'approved'
                    and (lower(split_part(p.name_en, ',', 1)) = lower(g.name_en) or lower(split_part(p.name_ru, ',', 1)) = lower(g.name_ru)));
`;
fs.writeFileSync(new URL('../supabase/migrations/20261106000300_fe_cities_15k.sql', import.meta.url), sql);
console.error('written', rows.length, 'cities,', (sql.length / 1e6).toFixed(2), 'MB');
