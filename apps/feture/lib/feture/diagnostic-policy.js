// @ts-check
'use strict';
// Privacy contract for FetUre diagnostics: never transmit or persist arbitrary
// Error.message, Error.stack, rejected values, URL paths, topic IDs or body data.
// Only fixed error family and server-approved runtime metadata survive.
const FAMILIES=Object.freeze(new Set([
 'Error','TypeError','ReferenceError','RangeError','SyntaxError','URIError',
 'EvalError','AggregateError','DOMException','AbortError','NetworkError'
]));
/** @param {unknown} input */
function safeFetureDiagnostic(input){
 const v=input&&typeof input==='object'&&!Array.isArray(input)?/** @type {Record<string,unknown>} */(input):{};
 const rawName=typeof v.name==='string'?v.name:'';
 const name=FAMILIES.has(rawName)?rawName:'Error';
 // Build identifier is generated by the bundler; permit a small non-URL alphabet.
 // Only the compile-time 12-character Git SHA or local `dev` build is expected.
 // Do not let arbitrary client-supplied strings use this field as diagnostic text.
 const build=typeof v.build==='string'&&/^(?:[0-9a-f]{12}|dev)$/.test(v.build)?v.build:'';
 return Object.freeze({
  action:'client_error',
  kind:v.kind==='rejection'?'rejection':'error',
  name,
  message:'feture_client_error',
  stack:'',
  build,
  platform:v.platform==='android'||v.platform==='ios'?v.platform:'web',
  locale:v.locale==='en'?'en':'ru'
 });
}
module.exports={safeFetureDiagnostic};
