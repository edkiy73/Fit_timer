import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const CHECK = process.argv.includes('--check');
const root = process.cwd();

async function readJson(file){
  return JSON.parse(await readFile(path.join(root, file), 'utf8'));
}

const product = await readJson('config/product.json');
const capacitor = await readJson('capacitor.config.json');

function requireString(name, value){
  if(typeof value !== 'string' || !value.trim()) throw new Error(`config/product.json: ${name} must be a non-empty string`);
  return value.trim();
}
function requireHttps(name, value){
  const raw = requireString(name, value);
  const url = new URL(raw);
  if(url.protocol !== 'https:') throw new Error(`config/product.json: ${name} must use https`);
  return raw.replace(/\/$/, '');
}

const appId = requireString('id', product.id);
const appName = requireString('name', product.name);
const slug = requireString('slug', product.slug);
requireHttps('defaultApiUrl', product.defaultApiUrl);
requireHttps('defaultPublicUrl', product.defaultPublicUrl);

if(!product.brand || typeof product.brand !== 'object') throw new Error('config/product.json: brand is required');
if(!product.features || typeof product.features !== 'object') throw new Error('config/product.json: features are required');
const uiThemes = product.brand.ui;
if(!uiThemes || typeof uiThemes !== 'object') throw new Error('config/product.json: brand.ui is required');
const uiKeys = ['background','card','surface','accent','accentInk'];
for(const mode of ['dark','light']){
  if(!uiThemes[mode] || typeof uiThemes[mode] !== 'object') throw new Error(`config/product.json: brand.ui.${mode} is required`);
  for(const key of uiKeys){
    const value = requireString(`brand.ui.${mode}.${key}`, uiThemes[mode][key]);
    if(!/^#[0-9A-Fa-f]{6}$/.test(value)) throw new Error(`config/product.json: brand.ui.${mode}.${key} must be #RRGGBB`);
  }
}

const featureKeys = ['profiles','premium','ai','notifications','biometrics','sharing'];
for(const key of featureKeys){
  if(typeof product.features[key] !== 'boolean') throw new Error(`config/product.json: features.${key} must be boolean`);
}

const mismatches = [];
if(capacitor.appId !== appId) mismatches.push(`capacitor appId=${capacitor.appId} expected ${appId}`);
if(capacitor.appName !== appName) mismatches.push(`capacitor appName=${capacitor.appName} expected ${appName}`);
if(capacitor.backgroundColor !== product.brand.background) mismatches.push('capacitor backgroundColor differs from product brand.background');
if(capacitor.plugins?.LocalNotifications?.iconColor !== product.brand.notificationAccent){
  mismatches.push('LocalNotifications.iconColor differs from product brand.notificationAccent');
}
if(mismatches.length) throw new Error('Product config mismatch:\n- ' + mismatches.join('\n- '));

const runtimeConfig = {
  appId,
  appName,
  slug,
  brand: product.brand,
  features: product.features,
  apiBase: '',
  publicAppUrl: ''
};
const rendered = `/* Generated by scripts/build-product-config.mjs. Public values only; no secrets. */\nwindow.APP_CONFIG = Object.freeze(${JSON.stringify(runtimeConfig, null, 2)});\n`;
const target = path.join(root, 'app.config.js');

if(CHECK){
  const current = await readFile(target, 'utf8');
  if(current !== rendered){
    console.error('app.config.js is stale. Run: npm run build:config');
    process.exit(1);
  }
  console.log('app.config.js: product config is in sync');
}else{
  const current = await readFile(target, 'utf8').catch(() => '');
  if(current !== rendered){
    await writeFile(target, rendered, 'utf8');
    console.log('rebuilt app.config.js');
  }else{
    console.log('app.config.js: unchanged');
  }
}
