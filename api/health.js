/* GET /api/health — «работает или нет», человеческим языком.

   Нужен затем, что настройка хранилища — единственный шаг, который нельзя сделать
   из кода: его делают мышкой в панели Vercel. Без такой страницы человек не может
   отличить «я неправильно нажал» от «нажал правильно, но приложение не видит», и
   это худшее место, где можно застрять.

   Отвечает простым текстом, а не JSON: это страница, которую открывают в браузере
   и читают глазами. */

const { store } = require('./_store');

module.exports = async (req, res) => {
  const i = store.info();
  const L = [];

  L.push('Fit Timer — состояние сервера');
  L.push('');

  if(i.connected){
    let err = null;
    try{ await store.selfTest(); }catch(e){ err = e && e.message; }
    if(!err){
      L.push('ХРАНИЛИЩЕ: подключено и работает.');
      L.push(`Переменные: ${i.vars[0]}, ${i.vars[1]}`);
      L.push('');
      L.push('Всё готово. Ссылки на программы работают.');
    } else {
      L.push('ХРАНИЛИЩЕ: переменные есть, но база не отвечает.');
      L.push(`Переменные: ${i.vars[0]}, ${i.vars[1]}`);
      L.push(`Ошибка: ${err}`);
      L.push('');
      L.push('Обычно это значит, что база удалена или токен устарел.');
      L.push('Проверь в панели Vercel: Storage → база на месте и подключена к проекту.');
    }
  } else if(i.memory){
    L.push('ХРАНИЛИЩЕ: память процесса (локальный запуск).');
    L.push('Так можно только на своём компьютере: на сервере данные пропадут.');
  } else {
    L.push('ХРАНИЛИЩЕ: НЕ ПОДКЛЮЧЕНО.');
    L.push('');
    if(i.redisUrlOnly){
      L.push('Похоже, база подключена не тем способом: есть REDIS_URL, а нужен');
      L.push('доступ по HTTP. При подключении выбирай Upstash for Redis —');
      L.push('он даёт нужные переменные сам.');
    } else {
      L.push('Что сделать (один раз, мышкой, ~2 минуты):');
      L.push('');
      L.push('  1. vercel.com → войти → открыть проект fittimer99');
      L.push('  2. вкладка Storage наверху');
      L.push('  3. Create Database → выбрать Upstash → Redis');
      L.push('  4. регион: ближе к людям (Frankfurt, если аудитория в России)');
      L.push('  5. план Free → Continue → Connect');
      L.push('  6. дождаться, пока проект пересоберётся (~минута)');
      L.push('  7. обновить эту страницу');
      L.push('');
      L.push('Ничего дописывать в коде не надо: переменные Vercel подставит сам.');
    }
    L.push('');
    L.push('Пока базы нет, приложение работает, но ссылки на программы');
    L.push('не создаются — программу можно передать только файлом.');
  }

  L.push('');
  L.push('— — —');
  L.push('Эта страница ничего не меняет и не показывает ни одного секрета.');

  res.statusCode = i.connected ? 200 : 503;
  res.setHeader('Content-Type', 'text/plain; charset=utf-8');
  res.setHeader('Cache-Control', 'no-store');
  res.end(L.join('\n'));
};
